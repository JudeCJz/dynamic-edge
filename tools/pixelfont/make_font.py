def rects(rows):
    """Merged horizontal runs as (x0, y0, x1, y1) in font units; row 0 is the top at y = 700."""
    out = []
    for r, row in enumerate(rows):
        y1 = 700 - r * U
        y0 = y1 - U
        x = 0
        while x < 5:
            if row[x] == '#':
                s = x
                while x < 5 and row[x] == '#':
                    x += 1
                out.append((s * U, y0, x * U, y1))
            else:
                x += 1
    return out


def glyph(rows):
    pen = TTGlyphPen(None)
    for x0, y0, x1, y1 in rects(rows):
        # 1 unit overlap so neighbouring runs never leave an anti-aliasing seam
        e = 1
        pen.moveTo((x0 - e, y0 - e))
        pen.lineTo((x0 - e, y1 + e))
        pen.lineTo((x1 + e, y1 + e))
        pen.lineTo((x1 + e, y0 - e))
        pen.closePath()
    return pen.glyph()


def main():
    order = [".notdef", "space"]
    cmap = {32: "space", 0xA0: "space"}
    glyphs = {}
    empty = TTGlyphPen(None).glyph()
    glyphs[".notdef"] = glyph(["#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"])
    glyphs["space"] = empty
    for ch, rows in G.items():
        cp = ord(ch)
        name = "uni%04X" % cp
        cmap[cp] = name
        order.append(name)
        glyphs[name] = glyph(rows)
    for cp in range(32, 127):
        assert cp in cmap, chr(cp)

    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics({n: (ADV, 0) for n in order})
    fb.setupHorizontalHeader(ascent=800, descent=-300)
    fb.setupNameTable({"familyName": "DynEdge Pixel", "styleName": "Regular"})
    fb.setupOS2(sTypoAscender=800, sTypoDescender=-300, usWinAscent=800, usWinDescent=300,
                sxHeight=500, sCapHeight=700, fsType=0)
    fb.setupPost(isFixedPitch=1)
    out = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..",
                                        "app", "src", "main", "res", "font", "pixel.ttf"))
    os.makedirs(os.path.dirname(out), exist_ok=True)
    fb.save(out)
    print("wrote", out, len(order), "glyphs")


if __name__ == "__main__":
    main()
